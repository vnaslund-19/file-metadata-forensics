"""Tests for .eml extraction. Run with: python -m unittest discover tests

The emails here are generated by the tests themselves, with example.com
addresses, so they don't depend on the real samples in samples/.
"""

import tempfile
import unittest
from email.message import EmailMessage
from pathlib import Path

from metadata_forensics import eml, scan


def write_email(folder, name="test.eml", **headers):
    message = EmailMessage()
    message["From"] = "Sender <sender@example.com>"
    message["To"] = "First <first@example.com>, second@example.com"
    message["Cc"] = "copy@example.com"
    message["Bcc"] = "hidden@example.com"
    message["Subject"] = "Generated test email"
    message["Date"] = "Tue, 13 Oct 2026 01:04:42 +1100"
    message["Message-ID"] = "<generated@example.com>"
    message["Received"] = "from relay.example.com by mx.example.com; Mon, 12 Oct 2026 14:05:18 +0000"
    message["Received"] = "by origin.example.com with SMTP; Mon, 12 Oct 2026 14:05:16 +0000"
    for name_, value in headers.items():
        del message[name_.replace("_", "-")]
        if value is not None:
            message[name_.replace("_", "-")] = value
    message.set_content("Plain body")
    message.add_alternative("<p>HTML body</p>", subtype="html")
    message.add_attachment(b"%PDF-1.3 test", maintype="application", subtype="pdf",
                           filename="report.pdf")
    path = Path(folder) / name
    path.write_bytes(message.as_bytes())
    return path


class EmailTests(unittest.TestCase):
    def setUp(self):
        self.folder = tempfile.TemporaryDirectory()
        self.addCleanup(self.folder.cleanup)

    def test_headers(self):
        details, warnings = eml.inspect(write_email(self.folder.name))
        metadata = details["metadata"]
        self.assertEqual(metadata["from"], "Sender <sender@example.com>")
        self.assertEqual(metadata["to"], "First <first@example.com>, second@example.com")
        self.assertEqual(metadata["cc"], "copy@example.com")
        self.assertEqual(metadata["bcc"], "hidden@example.com")
        self.assertEqual(metadata["subject"], "Generated test email")
        self.assertEqual(metadata["message_id"], "<generated@example.com>")
        self.assertEqual(warnings, [])

    def test_date_keeps_the_senders_offset(self):
        details, _ = eml.inspect(write_email(self.folder.name))
        self.assertEqual(details["metadata"]["sent"], "2026-10-13T01:04:42+11:00")

    def test_received_headers_in_file_order(self):
        details, _ = eml.inspect(write_email(self.folder.name))
        self.assertEqual(len(details["received"]), 2)
        self.assertTrue(details["received"][0].startswith("from relay.example.com"))

    def test_mime_structure_and_attachments(self):
        details, _ = eml.inspect(write_email(self.folder.name))
        self.assertEqual(details["mime_parts"], [
            "multipart/mixed",
            "  multipart/alternative",
            "    text/plain",
            "    text/html",
            "  application/pdf  attachment: report.pdf",
        ])
        self.assertEqual(details["embedded_objects"], ["report.pdf (application/pdf)"])

    def test_missing_headers_are_none(self):
        path = write_email(self.folder.name, Cc=None, Bcc=None, Received=None)
        details, _ = eml.inspect(path)
        self.assertIsNone(details["metadata"]["cc"])
        self.assertIsNone(details["metadata"]["bcc"])
        self.assertEqual(details["received"], [])

    def test_unparseable_date_is_kept_with_a_warning(self):
        path = Path(self.folder.name) / "bad_date.eml"
        path.write_bytes(b"From: sender@example.com\nDate: not a date\nSubject: x\n\nbody\n")
        details, warnings = eml.inspect(path)
        self.assertEqual(details["metadata"]["sent"], "not a date")
        self.assertTrue(any("Date" in warning for warning in warnings))

    def test_scan_result_has_the_shared_shape(self):
        result = scan.extract_metadata(write_email(self.folder.name))
        self.assertEqual(result["type"], "eml")
        self.assertEqual(set(result["metadata"]), set(scan.METADATA_FIELDS))
        self.assertIsNone(result["macros"])
        self.assertEqual(len(result["received"]), 2)

    def test_not_an_email_does_not_crash(self):
        path = Path(self.folder.name) / "junk.eml"
        path.write_bytes(b"\x00\x01 this is not an email \xff")
        result = scan.extract_metadata(path)
        self.assertEqual(result["type"], "eml")


if __name__ == "__main__":
    unittest.main()
