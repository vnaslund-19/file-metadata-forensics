"""Tests for image extraction. Run with: python -m unittest discover tests

The images are generated by the tests themselves with known EXIF values, so
they don't depend on the real photos in samples/.
"""

import tempfile
import unittest
from pathlib import Path

from PIL import ExifTags, Image, PngImagePlugin

from metadata_forensics import image, scan

TAGS = ExifTags.Base
GPS = ExifTags.GPS


def make_exif():
    exif = Image.Exif()
    exif[TAGS.Make] = "TestMake"
    exif[TAGS.Model] = "TestModel"
    exif[TAGS.Software] = "TestSoftware 1.0"
    exif[TAGS.DateTime] = "2026:01:02 06:07:08"
    exif[TAGS.Orientation] = 6
    details = exif.get_ifd(ExifTags.IFD.Exif)
    details[TAGS.DateTimeOriginal] = "2026:01:02 03:04:05"
    details[TAGS.OffsetTimeOriginal] = "-05:00"
    details[TAGS.UserComment] = b"ASCII\x00\x00\x00Generated"
    gps = exif.get_ifd(ExifTags.IFD.GPSInfo)
    gps[GPS.GPSLatitudeRef] = "S"
    gps[GPS.GPSLatitude] = (10.0, 30.0, 0.0)
    gps[GPS.GPSLongitudeRef] = "W"
    gps[GPS.GPSLongitude] = (20.0, 15.0, 0.0)
    gps[GPS.GPSAltitudeRef] = b"\x01"
    gps[GPS.GPSAltitude] = 5.0
    gps[GPS.GPSDateStamp] = "2026:01:02"
    gps[GPS.GPSTimeStamp] = (8.0, 4.0, 5.0)
    return exif


class ImageTests(unittest.TestCase):
    def setUp(self):
        folder = tempfile.TemporaryDirectory()
        self.addCleanup(folder.cleanup)
        self.folder = Path(folder.name)

    def write_jpeg(self, exif=None):
        path = self.folder / "test.jpg"
        Image.new("RGB", (40, 30)).save(path, exif=exif or Image.Exif())
        return path

    def test_jpeg_exif(self):
        details, warnings = image.inspect(self.write_jpeg(make_exif()))
        metadata = details["metadata"]
        self.assertEqual(metadata["camera_make"], "TestMake")
        self.assertEqual(metadata["camera_model"], "TestModel")
        self.assertEqual(metadata["application"], "TestSoftware 1.0")
        self.assertEqual(metadata["orientation"], "rotated 90 clockwise")
        self.assertEqual(metadata["comments"], "Generated")
        self.assertEqual((metadata["width"], metadata["height"]), (40, 30))
        self.assertEqual(warnings, [])

    def test_dates_keep_their_offset_or_have_none(self):
        metadata = image.inspect(self.write_jpeg(make_exif()))[0]["metadata"]
        self.assertEqual(metadata["created"], "2026-01-02T03:04:05-05:00")
        # No OffsetTime tag, so no offset is assumed.
        self.assertEqual(metadata["modified"], "2026-01-02T06:07:08")

    def test_gps_south_west_and_below_sea_level_are_negative(self):
        metadata = image.inspect(self.write_jpeg(make_exif()))[0]["metadata"]
        self.assertAlmostEqual(metadata["gps_latitude"], -10.5)
        self.assertAlmostEqual(metadata["gps_longitude"], -20.25)
        self.assertAlmostEqual(metadata["gps_altitude"], -5.0)
        self.assertEqual(metadata["gps_time"], "2026-01-02T08:04:05Z")

    def test_jpeg_without_exif(self):
        details, warnings = image.inspect(self.write_jpeg())
        self.assertEqual(details["metadata"]["width"], 40)
        self.assertNotIn("gps_latitude", details["metadata"])
        self.assertEqual(warnings, [])

    def test_png_text_chunks(self):
        path = self.folder / "test.png"
        info = PngImagePlugin.PngInfo()
        info.add_text("Software", "TestPainter")
        info.add_itxt("Author", "Test Author")
        Image.new("RGB", (10, 10)).save(path, pnginfo=info)
        metadata = image.inspect(path)[0]["metadata"]
        self.assertEqual(metadata["application"], "TestPainter")
        self.assertEqual(metadata["author"], "Test Author")
        self.assertFalse(metadata["has_xmp_metadata"])

    def test_scan_result_has_the_shared_shape(self):
        result = scan.extract_metadata(self.write_jpeg(make_exif()))
        self.assertEqual(result["type"], "jpeg")
        self.assertEqual(set(result["metadata"]), set(scan.METADATA_FIELDS))

    def test_not_an_image_does_not_crash(self):
        path = self.folder / "junk.jpg"
        path.write_bytes(b"this is not an image")
        result = scan.extract_metadata(path)
        self.assertTrue(any("could not read the image" in w for w in result["warnings"]))


if __name__ == "__main__":
    unittest.main()
